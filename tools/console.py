#!/usr/bin/env python3
"""Вывод на экран: одна защита от падения программы на собственном тексте.

Зачем это отдельный файл. Радар печатает по-русски, а в его строках попадаются
знаки, которых нет в кодировке Windows по умолчанию: минус «−» из отчёта
детектора и рубль «₽» из разбора цен. Пока вывод идёт в окно терминала, всё
хорошо: Python отдаёт его в консоль Windows напрямую и печатает что угодно.

Стоит перенаправить вывод в файл — а расписание делает ровно это, — как Python
переключается на кодировку системы (здесь cp1251), не находит в ней «−» и
роняет программу:

    UnicodeEncodeError: 'charmap' codec can't encode character '\u2212'

Проверено фактом до того, как расписание было написано: `python detect.py >
out.txt` падает на первой же строке с изменением. То есть радар, поставленный
на расписание без этой заплатки, умер бы в первый же день — и не на сети, не на
чужом сайте, а на собственном знаке минуса.

Правило простое:

* вывод в окно терминала оставляем как есть — Windows-консоль и так всё умеет,
  а насильный utf-8 превратил бы русский текст в кракозябры;
* вывод в файл или в канал переводим в utf-8, потому что файл кодировку
  системы не спрашивает;
* в обоих случаях просим не падать на незнакомом знаке, а печатать «?».
  Потерянный знак — мелочь, потерянный прогон — потерянный день наблюдения.
"""

import sys


def setup() -> None:
    """Сделать вывод безопасным. Вызывается первой строкой в main()."""
    for stream in (sys.stdout, sys.stderr):
        if stream is None:      # pythonw.exe: окна нет, потоков тоже
            continue
        try:
            if stream.isatty():
                stream.reconfigure(errors="replace")
            else:
                stream.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, OSError, ValueError):
            # Поток без reconfigure (подменённый, закрытый, не текстовый).
            # Защита не встала — это не повод не начинать прогон.
            pass

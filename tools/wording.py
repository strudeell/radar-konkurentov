#!/usr/bin/env python3
"""Как показать человеку длинную чужую строку и не соврать.

Радар цитирует чужие страницы, а строки на них бывают в тысячу символов. В
сообщение такое не влезает, поэтому строки укорачиваются — в семи местах: в
уликах срочного сообщения, в цитатах правил, в строках недельной сводки, в
окружении цены, на экране.

Все семь мест резали строку по букве, и 20.08.2026 это увидел владелец. В
сообщении о подорожании Mango Office пришло:

    ₽ было 1 000 → стало 1 400 ₽/мес (+40,0%)  · История вызовов и запись
    звонков в карточке клиента · Умный перевод звонка на от

Ровно восемьдесят символов окружения — и обрыв посреди слова «ответственного».
Читается это не как «строку укоротили», а как «сообщение пришло битым»: у
человека возникает вопрос, что ещё в нём потерялось и можно ли верить числам.
Для системы, которая существует ради доверия к своим сообщениям, это дорогая
мелочь. Тем более что места в сообщении было полно: Telegram принимает 4096
символов, а всё сообщение занимало 448.

Что делает эта программа:

1. **Режет по границе, а не по букве.** Сначала пробует границу, которая
   сохраняет смысл целиком: разделитель списка « · », тире, конец предложения,
   запятую. Не нашлось — по пробелу. Слово не разрывается никогда.
2. **Ставит «…».** Читатель должен видеть, что строка продолжается. Без метки
   укороченная цитата выглядит как полная и врёт.
3. **Не отдаёт больше, чем просили.** Многоточие входит в бюджет, а не
   добавляется сверх него.

Единственный случай, когда слово всё-таки рвётся, — одно слово длиннее лимита
целиком (ссылка, склеенный идентификатор). Тогда резать больше не по чему.
"""

ELLIPSIS = "…"

# Границы, по которым можно резать, от самой ценной к самой дешёвой. Первая —
# разделитель, которым разбор цен склеивает окружение числа: обрезав по нему,
# получаем целые строки страницы, а не их огрызки.
BOUNDARIES = (" · ", " — ", " – ", ". ", "! ", "? ", "; ", ", ", " ")

# Насколько далеко назад разрешено отступать ради целой границы. Отступив
# слишком далеко, вместо длинной улики получим три слова и многоточие —
# формально аккуратно, а по делу пусто.
KEEP_AT_LEAST = 0.6

# Хвосты, которые незачем оставлять перед многоточием.
TRAIL = " ·—–,.;:!?«"


def shorten(text, limit: int) -> str:
    """Укоротить строку до limit символов по границе слова, с «…» на конце."""
    text = " ".join(str(text or "").split())
    if len(text) <= limit:
        return text
    if limit <= len(ELLIPSIS):
        return ELLIPSIS[:limit]

    room = limit - len(ELLIPSIS)
    # Плюс один символ: если ровно на границе бюджета стоит пробел, обрезать
    # можно прямо по нему, ничего не теряя.
    window = text[:room + 1]

    for boundary in BOUNDARIES:
        cut = window.rfind(boundary)
        if cut >= room * KEEP_AT_LEAST:
            return text[:cut].rstrip(TRAIL) + ELLIPSIS

    # Одно слово длиннее лимита: резать больше не по чему.
    return text[:room].rstrip(TRAIL) + ELLIPSIS


def cut_at_word(text, limit: int) -> bool:
    """Проверка для регрессионных случаев: строка укорочена честно?

    Честно — это когда результат не длиннее лимита, а всё, что до многоточия,
    дословно совпадает с началом исходной строки и кончается на границе слова.
    """
    result = shorten(text, limit)
    source = " ".join(str(text or "").split())
    if len(result) > limit:
        return False
    if result == source:
        return True
    if not result.endswith(ELLIPSIS):
        return False
    head = result[:-len(ELLIPSIS)]
    if not source.startswith(head.rstrip(TRAIL)):
        return False
    tail = source[len(head.rstrip(TRAIL)):]
    # Слово не разорвано, если сразу за оставленным куском идёт пробел или
    # знак препинания — либо если резать было не по чему вовсе.
    return (not tail or tail[0] in TRAIL
            or " " not in source[:limit])
